# Shared configuration for the stackwatch x86-64 development VM.
# Sourced by the other scripts in this directory; not executable on its own.

# Where the disk image and seed ISO live. Deliberately outside the repo:
# the disk is 20G and must never be a candidate for git.
VM_DIR="${VM_DIR:-$HOME/vm/stackwatch}"

VM_DISK="$VM_DIR/disk.qcow2"
VM_SEED="$VM_DIR/seed.iso"
VM_PID="$VM_DIR/qemu.pid"
VM_LOG="$VM_DIR/console.log"
# QEMU monitor socket. The escape hatch for when ssh is broken: the serial
# console is write-only and the VM is headless, so without this there is no
# way to power the guest down gracefully.
VM_MONITOR="$VM_DIR/monitor.sock"

# Debian 13 "trixie" cloud image. The "generic" variant, not "genericcloud":
# genericcloud ships Debian's reduced cloud kernel, which cannot be relied on
# for the 9p modules the source share needs. generic carries the full driver set.
IMAGE_URL="https://cloud.debian.org/images/cloud/trixie/latest/debian-13-generic-amd64.qcow2"
IMAGE_SHA512="1207e6e3efaff8ee77ab7a32c156a3eea6a9e53f94cfc48efbd1f49ba554ca36ac62ab27395aa813a1775a8c0a393b1a1ce5377d9e5670f6113e3110c57fee4b"
IMAGE_CACHE="$VM_DIR/$(basename "$IMAGE_URL")"

VM_USER="${VM_USER:-tikeysus}"
VM_HOSTNAME="stackwatch-vm"
VM_MEM="${VM_MEM:-2G}"
VM_CPUS="${VM_CPUS:-4}"
VM_DISK_SIZE="${VM_DISK_SIZE:-20G}"

# 2223 so this never collides with the Kali VM on 2222. ssh stores
# known_hosts entries per-port ([localhost]:2223), so the two coexist.
VM_SSH_PORT="${VM_SSH_PORT:-2223}"

# Host path shared into the guest over 9p, and the tag the guest mounts.
SHARE_PATH="${SHARE_PATH:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
SHARE_TAG="stackwatch"
SHARE_MOUNT="/home/$VM_USER/stackwatch"

# A key dedicated to this VM, generated by make-seed.sh if absent, with no
# passphrase so the scripts can log in unattended. Deliberately NOT the user's
# real identity key: that one is passphrase-protected, which makes every
# non-interactive ssh fail in a thoroughly misleading way -- the server
# accepts the key, then the client cannot sign and reports
# "Permission denied (publickey)". This key authorizes nothing but a
# loopback-only guest on port $VM_SSH_PORT.
VM_SSH_KEY="${VM_SSH_KEY:-$VM_DIR/id_vm}"
SSH_PUBKEY="${SSH_PUBKEY:-$VM_SSH_KEY.pub}"

# A known_hosts file private to this VM. Rebuilding the VM regenerates its
# host keys, which against the global ~/.ssh/known_hosts shows up as the
# scary REMOTE HOST IDENTIFICATION HAS CHANGED error and blocks login --
# accept-new accepts an unknown key but refuses a changed one. Keeping the
# file here means a rebuild is self-healing and the user's real known_hosts
# is never touched.
VM_KNOWN_HOSTS="$VM_DIR/known_hosts"

ssh_vm() {
	# 30s, not the usual 5: this guest is TCG-emulated, and a key exchange
	# that takes well under a second on real hardware can take many seconds
	# here. A short timeout aborts mid-handshake and looks exactly like an
	# auth failure.
	# IdentitiesOnly stops ssh from also offering every key in ~/.ssh, which
	# would otherwise hit the server's MaxAuthTries before reaching this one.
	ssh -p "$VM_SSH_PORT" \
		-o ConnectTimeout=30 \
		-o StrictHostKeyChecking=accept-new \
		-o UserKnownHostsFile="$VM_KNOWN_HOSTS" \
		-o IdentitiesOnly=yes \
		-i "$VM_SSH_KEY" \
		"$VM_USER@localhost" "$@"
}
